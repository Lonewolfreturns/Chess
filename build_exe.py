"""Build Wizard War Chess into a Windows executable with PyInstaller.

    python build_exe.py            -> dist/WizardWarChess.exe        (single file, easy to share)
    python build_exe.py --onedir   -> dist/WizardWarChess/ folder    (starts faster)

Requirements: pip install -r requirements.txt
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
os.chdir(ROOT)

# Qt pieces the game never uses - dropping them makes the .exe smaller and faster to start.
EXCLUDE_PARTS = [
    "opengl32sw.dll", "Qt6Pdf", "qml/QtQuick/Pdf", "Qt6Quick3DPhysics", "qml/QtQuick3D/Physics",
    "qml/QtPositioning", "Qt6Positioning", "qml/QtSensors", "Qt6Sensors", "qml/QtTextToSpeech",
    "Qt6TextToSpeech", "qml/QtRemoteObjects", "Qt6RemoteObjects", "qml/QtTest", "Qt6QuickTest",
    "qml/QtWebChannel", "Qt6WebChannel", "qml/QtWebSockets", "Qt6WebSockets", "VirtualKeyboard",
    "qml/QtQuick/Controls/Imagine", "Qt6QuickControls2Imagine", "qml/QtQuick/Controls/Material",
    "Qt6QuickControls2Material", "qml/QtQuick/Controls/Universal", "Qt6QuickControls2Universal",
    "qml/QtQuick/Controls/FluentWinUI3", "Qt6QuickControls2FluentWinUI3",
]

SPEC = r'''
# Generated by build_exe.py
EXCLUDE_PARTS = {excludes!r}

def keep(entry):
    dest = entry[0].replace("\\", "/")
    return not any(part in dest for part in EXCLUDE_PARTS)

a = Analysis(
    [{main!r}],
    pathex=[{root!r}],
    datas=[({qml!r}, "scene3d/qml"), ({assets!r}, "assets")],
    hiddenimports=["PyQt6.QtQuick3D", "PyQt6.QtQuickWidgets", "PyQt6.QtQuick", "PyQt6.QtQml",
                   "PyQt6.QtMultimedia"],
    excludes=["numpy", "tkinter", "PIL", "matplotlib", "PyQt6.QtWebEngineCore", "PyQt6.QtWebEngineWidgets",
              "PyQt6.QtPdf", "PyQt6.QtBluetooth", "PyQt6.QtNfc", "PyQt6.QtSql", "PyQt6.QtTest"],
)
a.binaries = [b for b in a.binaries if keep(b)]
a.datas = [d for d in a.datas if keep(d)]
pyz = PYZ(a.pure)
{tail}
'''

ONEFILE_TAIL = '''exe = EXE(pyz, a.scripts, a.binaries, a.datas, [], name="WizardWarChess", console=False,
          icon={icon!r}, upx=False, runtime_tmpdir=None)'''

ONEDIR_TAIL = '''exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name="WizardWarChess", console=False,
          icon={icon!r}, upx=False)
coll = COLLECT(exe, a.binaries, a.datas, name="WizardWarChess", upx=False)'''


def make_icon(path: str) -> bool:
    from PyQt6.QtGui import QGuiApplication, QImage
    app = QGuiApplication.instance() or QGuiApplication(sys.argv)  # noqa: F841
    sys.path.insert(0, ROOT)
    import chess
    from ui.piece_graphics import PieceRenderer
    from ui.theme import ARMY_STYLES
    from ui.widgets import avatar_pixmap
    pix = avatar_pixmap(PieceRenderer(), ARMY_STYLES["celestial_arcane"], chess.WHITE, 256)
    img = pix.toImage().convertToFormat(QImage.Format.Format_ARGB32)
    return img.save(path, "ICO")


def main():
    onedir = "--onedir" in sys.argv
    os.makedirs("build_assets", exist_ok=True)
    icon = os.path.abspath(os.path.join("build_assets", "icon.ico"))
    if not make_icon(icon):
        icon = None
    tail = (ONEDIR_TAIL if onedir else ONEFILE_TAIL).format(icon=icon)
    spec = SPEC.format(excludes=EXCLUDE_PARTS, main=os.path.join(ROOT, "main.py"), root=ROOT,
                       qml=os.path.join(ROOT, "scene3d", "qml"), assets=os.path.join(ROOT, "assets"), tail=tail)
    spec_path = os.path.join("build_assets", "WizardWarChess.spec")
    with open(spec_path, "w", encoding="utf-8") as f:
        f.write(spec)
    cmd = [sys.executable, "-m", "PyInstaller", spec_path, "--noconfirm", "--clean",
           "--distpath", os.path.join(ROOT, "dist"), "--workpath", os.path.join(ROOT, "build")]
    print("Running:", " ".join(cmd))
    result = subprocess.run(cmd)
    if result.returncode != 0:
        sys.exit(result.returncode)
    target = os.path.join(ROOT, "dist", "WizardWarChess" if onedir else "WizardWarChess.exe")
    print("\nBuilt:", target)
    if not onedir:
        print("Size: %.1f MB" % (os.path.getsize(target) / 1e6))


if __name__ == "__main__":
    main()
